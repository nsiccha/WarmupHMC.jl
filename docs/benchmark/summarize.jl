# Turns results/runs.json into the markdown tables in RESULTS.md.
#
#   julia --project=docs/benchmark docs/benchmark/summarize.jl [runs.json]
#
# Separate from the driver on purpose: the tables can be regenerated, checked
# and corrected from the checked-in JSON without spending another benchmark run.

import JSON
using Statistics, Printf

const RUNS = length(ARGS) >= 1 ? ARGS[1] :
             joinpath(@__DIR__, "results", "runs.json")

raw = JSON.parse(read(RUNS, String))
runs = raw["runs"]

# JSON has no NaN, so the writer emitted `null` for every non-finite measurement.
num(x) = x === nothing ? NaN : Float64(x)
vals(rs, k) = [num(r[k]) for r in rs if r["ok"] && isfinite(num(r[k]))]
med(rs, k) = (v = vals(rs, k); isempty(v) ? NaN : median(v))
lo(rs, k)  = (v = vals(rs, k); isempty(v) ? NaN : minimum(v))
hi(rs, k)  = (v = vals(rs, k); isempty(v) ? NaN : maximum(v))

const ARM_ORDER = ["plain", "fixed_centered", "adaptive", "fixed_noncentered", "sibling_plain"]
const ARM_LABEL = Dict(
    "plain"             => "plain (no wrapper)",
    "fixed_centered"    => "fixed c = centered",
    "adaptive"          => "**adaptive** (starts centered)",
    "fixed_noncentered" => "fixed c = noncentered",
    "sibling_plain"     => "hand-written noncentered model",
)

targets = unique([r["target"] for r in runs])
arms_of(t) = [a for a in ARM_ORDER if any(r -> r["target"] == t && r["arm"] == a, runs)]
rows_of(t, a) = [r for r in runs if r["target"] == t && r["arm"] == a]

"""
Min ESS over the constrained parameters that EVERY arm of this target reports.

The hand-written noncentered sibling declares more constrained parameters than
the centered model it is being compared against, so a min over each model's own
full set is a min over different quantities. Intersecting first makes the
comparison an apples-to-apples one.
"""
function shared_constrained(t)
    sets = Vector{Set{String}}()
    for a in arms_of(t), r in rows_of(t, a)
        r["ok"] || continue
        nm = get(r, "con_names", nothing)
        (nm === nothing || isempty(nm)) && continue
        push!(sets, Set(String.(nm)))
    end
    isempty(sets) ? Set{String}() : reduce(intersect, sets)
end

function matched_min_ess(r, shared)
    nm = get(r, "con_names", nothing)
    es = get(r, "ess_con", nothing)
    (nm === nothing || es === nothing || isempty(nm) || isempty(es)) && return NaN
    v = [num(es[i]) for i in eachindex(nm) if String(nm[i]) in shared]
    v = filter(isfinite, v)
    isempty(v) ? NaN : minimum(v)
end

fmt(x; d = 1) = isfinite(x) ? string(round(x; digits = d)) : "—"
rng(rs, k; d = 1) = isfinite(med(rs, k)) ?
    @sprintf("%s <sub>%s–%s</sub>", fmt(med(rs, k); d), fmt(lo(rs, k); d), fmt(hi(rs, k); d)) : "—"

println("<!-- generated by docs/benchmark/summarize.jl from results/runs.json -->")
println()
@printf("%d seeds per arm, n_draws floor %d, julia %s, BLAS threads %s.\n\n",
        raw["n_seeds"], raw["n_draws_floor"], raw["julia"], raw["blas_threads"])

for t in targets
    trows = [r for r in runs if r["target"] == t]
    note = trows[1]["note"]
    dim = trows[1]["dim"]
    println("### `", t, "`")
    println()
    println("*", note, " — dimension ", dim, ".*")
    println()
    shared = shared_constrained(t)
    println("| arm | min ESS | ESS/sec | ESS per 1k grad | grad evals | divergences | final source `c` |")
    println("|---|---|---|---|---|---|---|")
    for a in arms_of(t)
        rs = rows_of(t, a)
        cs = [c for r in rs if r["ok"] for c in num.(get(r, "c_after", []))]
        cstr = isempty(cs) ? "—" : fmt(median(cs); d = 2)
        @printf("| %s | %s | %s | %s | %s | %s | %s |\n",
                get(ARM_LABEL, a, a),
                rng(rs, "ess_min"),
                rng(rs, "ess_min_per_s"),
                isfinite(med(rs, "ess_min_per_grad")) ?
                    fmt(1000 * med(rs, "ess_min_per_grad"); d = 2) : "—",
                fmt(med(rs, "grad_evals"); d = 0),
                fmt(med(rs, "n_divergent"); d = 1),
                cstr)
    end
    println()

    if !isempty(shared)
        println("Min ESS over the ", length(shared),
                " constrained parameters all arms share, so the differently-parametrized ",
                "models above are compared on the same quantities:")
        println()
        println("| arm | matched min ESS | per 1k grad |")
        println("|---|---|---|")
        for a in arms_of(t)
            rs = rows_of(t, a)
            v = filter(isfinite, [matched_min_ess(r, shared) for r in rs if r["ok"]])
            g = filter(isfinite, [num(r["grad_evals"]) for r in rs if r["ok"]])
            @printf("| %s | %s | %s |\n", get(ARM_LABEL, a, a),
                    isempty(v) ? "—" : fmt(median(v)),
                    (isempty(v) || isempty(g)) ? "—" :
                        fmt(1000 * median(v) / median(g); d = 2))
        end
        println()
    end

    nfail = count(r -> !r["ok"], trows)
    nfail == 0 || println("*", nfail, " of ", length(trows), " runs failed on this target.*\n")
end

ov = JSON.parse(read(joinpath(dirname(RUNS), "gradient_overhead.json"), String))
println("### Gradient-path overhead")
println()
println("Nanoseconds per `logdensity_and_gradient` call, ", ov[1]["n_calls"],
        " calls at random positions.")
println()
println("| target | bare | wrapped, no-op | wrapped, live | no-op cost | live cost |")
println("|---|---|---|---|---|---|")
for o in ov
    @printf("| `%s` | %s | %s | %s | ×%s | ×%s |\n", o["target"],
            fmt(num(o["bare_ns"]); d = 0), fmt(num(o["noop_ns"]); d = 0),
            fmt(num(o["live_ns"]); d = 0),
            fmt(num(o["noop_ratio"]); d = 2), fmt(num(o["live_ratio"]); d = 2))
end
